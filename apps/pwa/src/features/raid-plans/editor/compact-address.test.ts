import { describe, expect, it } from 'vitest'
import { compactRouteAddress } from './compact-address'

describe('compact route addresses', () => {
  it.each([
    ['10А, Пушкинская улица, Октябрьский район, Ижевск, Удмуртская Республика, 426000, Россия', 'Пушкинская улица, 10А'],
    ['Ижевск, улица Ленина, 42/1', 'улица Ленина, 42/1'],
    ['улица 9 Января, 12, Ижевск, Россия', 'улица 9 Января, 12'],
    ['Набережная Зодчего Дудина, Ижевск, Россия', 'Набережная Зодчего Дудина'],
    ['Лесная поляна, Октябрьский район, Ижевск, Россия', 'Лесная поляна'],
    ['У старого дуба', 'У старого дуба'],
    ['', ''],
  ])('shortens %s', (value, expected) => expect(compactRouteAddress(value)).toBe(expected))
})
